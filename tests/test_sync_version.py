class FakeRepo:
    """暫存目錄中的假 repo。"""

    def __init__(self, root: Path) -> None:
        self.root = root

    def write(self, relative: str, text: str, newline: str = "\n") -> Path:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline=newline) as f:
            f.write(text)
        return path

    def read(self, relative: str) -> str:
        with (self.root / relative).open(encoding="utf-8", newline="") as f:
            return f.read()

    def setup(self, project: str = "1.2.3", app: str = "1.2.3") -> None:
        self.write("pyproject.toml", PYPROJECT.format(version=project))
        for relative, template in FILES.items():
            self.write(relative, template.format(version=app))


class SyncVersionTestCase(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.repo = FakeRepo(Path(tmp.name))
        self.lines: list[str] = []

    def run_cmd(self, *args: str) -> int:
        return sv.run_command(list(args), self.repo.root, self.lines.append)


class ReadAndCheckTest(SyncVersionTestCase):
    def test_reads_every_existing_target(self) -> None:
        self.repo.setup("1.2.3", "1.2.3")
        versions = {
            f.path.relative_to(self.repo.root).as_posix(): f.version
            for f in sv.current_versions(self.repo.root)
        }
        self.assertEqual(versions, dict.fromkeys(FILES, "1.2.3"))
        self.assertEqual(self.run_cmd("check"), 0)
        self.assertEqual(sv.mismatches(self.repo.root), [])

    def test_check_reports_each_mismatch(self) -> None:
        self.repo.setup("1.2.4", "1.2.3")
        self.assertEqual(self.run_cmd("check"), 1)
        mismatched = [line for line in self.lines if line.startswith("MISMATCH")]
        self.assertEqual(len(mismatched), len(FILES))
        self.assertIn("1.2.3 != 1.2.4", mismatched[0])

    def test_missing_app_files_are_skipped(self) -> None:
        self.repo.write("pyproject.toml", PYPROJECT.format(version="0.1.0"))
        self.assertEqual(sv.current_versions(self.repo.root), [])
        self.assertEqual(self.run_cmd("check"), 0)
        self.assertEqual(sv.sync(self.repo.root), [])

    def test_package_lock_with_two_different_versions_is_a_mismatch(self) -> None:
        self.repo.setup("1.2.3", "1.2.3")
        text = self.repo.read("app/package-lock.json")
        self.repo.write(
            "app/package-lock.json",
            text.replace(
                '"version": "1.2.3",\n      "devDependencies"',
                '"version": "1.0.0",\n      "devDependencies"',
            ),
        )
        self.assertEqual(self.run_cmd("check"), 1)

    def test_non_semver_project_version_is_an_error(self) -> None:
        self.repo.setup("1.2", "1.2.3")
        self.assertEqual(self.run_cmd("check"), 1)
        self.assertIn("not a SemVer", self.lines[-1])

    def test_pep440_only_version_is_rejected(self) -> None:
        self.repo.setup("1.2.3.dev1", "1.2.3")
        with self.assertRaises(sv.VersionError):
            sv.project_version(self.repo.root)

    def test_invalid_json_is_reported_with_path(self) -> None:
        self.repo.setup()
        self.repo.write("app/package.json", "{ not json")
        self.assertEqual(self.run_cmd("check"), 1)
        self.assertIn("package.json", self.lines[-1])

    def test_unknown_command_is_usage_error(self) -> None:
        self.repo.setup()
        self.assertEqual(self.run_cmd("frobnicate"), 2)
        self.assertEqual(self.run_cmd("bump", "huge"), 2)


class SyncTest(SyncVersionTestCase):
    def test_sync_changes_only_the_version_strings(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        before = {relative: self.repo.read(relative) for relative in FILES}
        changed = sv.sync(self.repo.root)
        self.assertEqual(len(changed), len(FILES))
        for relative, template in FILES.items():
            after = self.repo.read(relative)
            self.assertEqual(after, template.format(version="2.0.0"), relative)
            self.assertNotEqual(after, before[relative])
        # 其他同名的 version 欄位不能被動到。
        self.assertIn(
            '"version": "keep-me"', self.repo.read("app/src-tauri/tauri.conf.json")
        )
        cargo = tomllib.loads(self.repo.read("app/src-tauri/Cargo.toml"))
        self.assertEqual(cargo["dependencies"]["tauri"]["version"], "=2.12.5")
        self.assertEqual(cargo["dependencies"]["serde"]["version"], "1.0.0")
        lock = tomllib.loads(self.repo.read("app/src-tauri/Cargo.lock"))
        self.assertEqual(
            {p["name"]: p["version"] for p in lock["package"]},
            {"aho-corasick": "1.1.3", "kikitori-app": "2.0.0", "tauri": "2.12.5"},
        )
        self.assertIn(
            '"node_modules/vite": {\n      "version": "7.0.0"',
            self.repo.read("app/package-lock.json"),
        )
        self.assertEqual(self.run_cmd("check"), 0)

    def test_sync_is_idempotent(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        sv.sync(self.repo.root)
        self.assertEqual(sv.sync(self.repo.root), [])
        self.assertEqual(self.run_cmd("sync"), 0)
        self.assertIn("already in sync", self.lines[-1])

    def test_sync_preserves_crlf_line_endings(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        self.repo.write(
            "app/package.json", PACKAGE_JSON.format(version="1.2.3"), newline="\r\n"
        )
        sv.sync(self.repo.root)
        text = self.repo.read("app/package.json")
        self.assertEqual(
            text, PACKAGE_JSON.format(version="2.0.0").replace("\n", "\r\n")
        )

    def test_sync_refuses_file_without_version_and_writes_nothing(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        self.repo.write("app/package.json", '{\n  "name": "kikitori-app"\n}\n')
        self.assertEqual(self.run_cmd("sync"), 1)
        self.assertIn("package.json", self.lines[-1])
        self.assertEqual(
            self.repo.read("app/package.json"), '{\n  "name": "kikitori-app"\n}\n'
        )

    def test_cargo_lock_without_own_package_is_an_error(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        self.repo.write(
            "app/src-tauri/Cargo.lock",
            'version = 4\n\n[[package]]\nname = "tauri"\nversion = "2.12.5"\n',
        )
        with self.assertRaises(sv.VersionError):
            sv.sync(self.repo.root)


class BumpTest(SyncVersionTestCase):
    def test_bumped(self) -> None:
        self.assertEqual(sv.bumped("1.2.3", "patch"), "1.2.4")
        self.assertEqual(sv.bumped("1.2.3", "minor"), "1.3.0")
        self.assertEqual(sv.bumped("1.2.3", "major"), "2.0.0")
        with self.assertRaises(sv.VersionError):
            sv.bumped("1.2.3-rc.1", "patch")
        with self.assertRaises(ValueError):
            sv.bumped("1.2.3", "huge")  # type: ignore[arg-type]

    def test_bump_rewrites_project_version_only_and_syncs(self) -> None:
        self.repo.setup("1.2.3", "1.2.3")
        self.assertEqual(sv.bump(self.repo.root, "minor"), "1.3.0")
        pyproject = self.repo.read("pyproject.toml")
        self.assertEqual(pyproject, PYPROJECT.format(version="1.3.0"))
        # [tool.something] 的 version 不是專案版本，不能被改。
        self.assertIn('[tool.something]\nversion = "9.9.9"', pyproject)
        self.assertEqual(sv.mismatches(self.repo.root), [])

    def test_bump_and_sync_work_on_crlf_toml_files(self) -> None:
        # Windows 上 git 的 core.autocrlf=true 會把 checkout 的 TOML 轉成 CRLF；
        # `[project]` 標題行結尾的 `\r` 不能讓區段比對失敗，也要保留原本的換行。
        self.repo.setup("1.2.3", "1.2.3")
        self.repo.write(
            "pyproject.toml", PYPROJECT.format(version="1.2.3"), newline="\r\n"
        )
        self.repo.write(
            "app/src-tauri/Cargo.toml",
            CARGO_TOML.format(version="1.2.3"),
            newline="\r\n",
        )
        self.assertEqual(sv.bump(self.repo.root, "minor"), "1.3.0")
        self.assertEqual(
            self.repo.read("pyproject.toml"),
            PYPROJECT.format(version="1.3.0").replace("\n", "\r\n"),
        )
        self.assertEqual(
            self.repo.read("app/src-tauri/Cargo.toml"),
            CARGO_TOML.format(version="1.3.0").replace("\n", "\r\n"),
        )
        self.assertEqual(sv.mismatches(self.repo.root), [])
        # 標題行帶註解時也一樣（`#.*` 不能把 `\r` 留給 `$`）
        text = '[project] # 專案\r\nname = "x"\r\nversion = "1.0.0"\r\n'
        self.assertEqual(
            sv.replace_toml_section_version(text, "project", "2.0.0"),
            text.replace("1.0.0", "2.0.0"),
        )

    def test_bump_command_runs_uv_lock(self) -> None:
        self.repo.setup("1.2.3", "1.2.3")
        with mock.patch.object(
            sv, "update_uv_lock", return_value="uv.lock updated"
        ) as uv_lock:
            self.assertEqual(self.run_cmd("bump", "patch"), 0)
        uv_lock.assert_called_once_with(self.repo.root)
        self.assertEqual(sv.project_version(self.repo.root), "1.2.4")


class UvLockTest(unittest.TestCase):
    def test_reports_missing_uv(self) -> None:
        with mock.patch.object(sv.shutil, "which", return_value=None):
            self.assertIn("uv not found", sv.update_uv_lock(Path(".")))

    def test_runs_uv_lock_with_timeout(self) -> None:
        run = mock.Mock(return_value=subprocess.CompletedProcess(["uv"], 0, "", ""))
        with mock.patch.object(sv.shutil, "which", return_value="/usr/bin/uv"):
            self.assertEqual(sv.update_uv_lock(Path("/repo"), run), "uv.lock updated")
        self.assertEqual(run.call_args.args[0], ["/usr/bin/uv", "lock"])
        self.assertEqual(run.call_args.kwargs["timeout"], sv.UV_LOCK_TIMEOUT_SECS)

    def test_reports_failure_and_timeout(self) -> None:
        failing = mock.Mock(
            return_value=subprocess.CompletedProcess(["uv"], 2, "", "boom")
        )
        hanging = mock.Mock(side_effect=subprocess.TimeoutExpired(["uv"], 1))
        with mock.patch.object(sv.shutil, "which", return_value="uv"):
            self.assertIn("boom", sv.update_uv_lock(Path("."), failing))
            self.assertIn("timed out", sv.update_uv_lock(Path("."), hanging))


def scripted(*answers: str) -> mock.Mock:
    it: Iterator[str] = iter(answers)

    def fake_input(prompt: str) -> str:
        try:
            return next(it)
        except StopIteration:
            raise EOFError from None

    return mock.Mock(side_effect=fake_input)


class MenuTest(SyncVersionTestCase):
    def test_menu_runs_selected_commands_until_exit(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        code = sv.menu(
            self.repo.root, scripted("3", "2", "3", "x", "7"), self.lines.append
        )
        self.assertEqual(code, 0)
        self.assertTrue(any(line.startswith("MISMATCH") for line in self.lines))
        self.assertIn("all versions match 2.0.0", self.lines)
        self.assertIn("無效的選項：'x'", self.lines)

    def test_menu_eof_returns_last_status(self) -> None:
        self.repo.setup("2.0.0", "1.2.3")
        self.assertEqual(sv.menu(self.repo.root, scripted("3"), self.lines.append), 1)


