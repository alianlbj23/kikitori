"""Copies the engine's message-code catalog into a UI test fixture.

Role: `src/kikitori/hardware/messages.py` (`CATALOG`) is the single source of the
`{code, params, message}` codes the engine sends; the UI translates each one with
its dictionary key `engine.<code>`. This script writes the code list (parameter
names, types, English template) to
`app/src/lib/testdata/engine-message-codes.json`, and `src/locales/engine-codes.test.ts`
checks that every code has a dictionary entry with exactly those placeholders.

It reads the catalog with `ast` instead of importing it, so it needs only the
standard library (`uv run --no-project python app/dev/extract_message_codes.py`,
or item "更新引擎訊息碼清單" in `npm run menu`) and never runs project code.
Run it whenever messages.py gains or changes a code; the test then shows which
dictionary entries are missing.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE = REPO_ROOT / "src" / "kikitori" / "hardware" / "messages.py"
TARGET = REPO_ROOT / "app" / "src" / "lib" / "testdata" / "engine-message-codes.json"
TYPE_NAMES = {"str": "str", "int": "int", "float": "float"}


class CatalogError(Exception):
    """messages.py no longer has the shape this script understands."""


def _catalog_dict(tree: ast.Module) -> ast.Dict:
    """The dict literal inside `CATALOG = MappingProxyType({...})`."""
    for node in tree.body:
        target = node.target if isinstance(node, ast.AnnAssign) else None
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
        if not (isinstance(target, ast.Name) and target.id == "CATALOG"):
            continue
        value = node.value
        if (
            isinstance(value, ast.Call)
            and len(value.args) == 1
            and isinstance(value.args[0], ast.Dict)
        ):
            return value.args[0]
        raise CatalogError("CATALOG is not MappingProxyType({...})")
    raise CatalogError("CATALOG not found")


def _spec(code: str, call: ast.expr) -> dict[str, Any]:
    """`_spec("English {x}", x=str)` → {params, types, english}."""
    if not (
        isinstance(call, ast.Call)
        and isinstance(call.func, ast.Name)
        and call.func.id == "_spec"
        and len(call.args) == 1
        and isinstance(call.args[0], ast.Constant)
        and isinstance(call.args[0].value, str)
    ):
        raise CatalogError(f"{code}: expected _spec(<string literal>, name=type, ...)")
    params: list[str] = []
    types: dict[str, str] = {}
    for keyword in call.keywords:
        if keyword.arg is None or not isinstance(keyword.value, ast.Name):
            raise CatalogError(f"{code}: parameters must be name=str|int|float")
        type_name = TYPE_NAMES.get(keyword.value.id)
        if type_name is None:
            raise CatalogError(f"{code}.{keyword.arg}: unknown type {keyword.value.id}")
        params.append(keyword.arg)
        types[keyword.arg] = type_name
    return {"params": params, "types": types, "english": call.args[0].value}


def extract(source: str) -> dict[str, dict[str, Any]]:
    """Code → spec, in catalog order."""
    catalog = _catalog_dict(ast.parse(source))
    codes: dict[str, dict[str, Any]] = {}
    for key, value in zip(catalog.keys, catalog.values, strict=True):
        if not (isinstance(key, ast.Constant) and isinstance(key.value, str)):
            raise CatalogError("CATALOG keys must be string literals")
        if key.value in codes:
            raise CatalogError(f"duplicate code {key.value}")
        codes[key.value] = _spec(key.value, value)
    if not codes:
        raise CatalogError("CATALOG is empty")
    return codes


def main() -> int:
    try:
        codes = extract(SOURCE.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, CatalogError) as exc:
        print(f"cannot read the message catalog from {SOURCE}: {exc}", file=sys.stderr)
        return 1
    document = {
        "_comment": (
            "Generated by app/dev/extract_message_codes.py from "
            "src/kikitori/hardware/messages.py CATALOG; do not edit by hand."
        ),
        "codes": codes,
    }
    TARGET.write_text(
        json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"wrote {len(codes)} codes to {TARGET.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
